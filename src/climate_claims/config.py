import os
from dataclasses import dataclass
from pathlib import Path

from dotenv import load_dotenv

load_dotenv()


def _env(*names: str, default: str = "") -> str:
    """First non-empty environment variable among `names`."""
    for name in names:
        value = os.environ.get(name, "").strip()
        if value:
            return value
    return default


def _base_url() -> str:
    explicit = _env("LLM_BASE_URL")
    if explicit:
        return explicit.rstrip("/")
    legacy = _env("OPENWEBUI_URL")           # old variable: server root, chat lives under /api
    return f"{legacy.rstrip('/')}/api" if legacy else ""


@dataclass(frozen=True)
class Settings:
    # --- LLM connection (environment / .env only; never put keys in code) ---
    # provider "openai"    = any OpenAI-compatible server (OpenAI, OpenRouter, Open WebUI,
    #                        Ollama, vLLM, LM Studio ...). base_url ends right before /chat/completions.
    # provider "anthropic" = Claude API (base_url defaults to https://api.anthropic.com)
    llm_provider: str = _env("LLM_PROVIDER", default="openai").lower()
    llm_base_url: str = _base_url()
    llm_api_key: str = _env("LLM_API_KEY", "OPENWEBUI_API_KEY")
    llm_model: str = _env("LLM_MODEL", "OPENWEBUI_MODEL")

    # --- paths (relative to where you run the command) ---
    raw_dir: Path = Path("data/raw/01_assessments/ipcc_ar6_wg1")
    sources_file: Path = Path("data/raw/sources.json")
    index_dir: Path = Path("data/index")
    provenance_file: Path = Path("data/index/provenance.json")   # made by `claims provenance`
    figure_links_file: Path = Path("data/figure_links.json")     # optional: per-figure page / data / code links
    runs_dir: Path = Path("runs")
    web_dir: Path = Path("docs")             # GitHub Pages site, generated by `claims export-web`

    # --- index-time: changing these requires `claims index --rebuild` ---
    emb_model: str = "BAAI/bge-small-en-v1.5"
    min_words: int = 8          # shorter sentences are stored for context but not embedded

    # --- query-time: free to change, no rebuild ---
    context: int = 7            # sentences kept before AND after each hit
    top_k: int = 6             # sentence hits per query

    llm_timeout: int = int(os.environ.get("LLM_TIMEOUT", "600"))   # seconds
    llm_workers: int = int(os.environ.get("LLM_WORKERS", "4"))     # parallel LLM calls (1 = sequential)


settings = Settings()
